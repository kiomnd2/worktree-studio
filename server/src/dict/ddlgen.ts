/**
 * ERD 테이블·컬럼·관계로 DBMS별 DDL을 만든다. erd-vibe 프론트 utils/ddlGenerator.js 규칙을 옮겼다.
 * 관계 방향: from = PK를 가진 쪽(1), to = FK를 가진 쪽(N). FK는 to 테이블에 ALTER TABLE로 붙인다.
 */

export type GenColumn = {
  id: string; physical_name: string; logical_name?: string | null; data_type: string | null; data_length?: string | number | null;
  is_primary_key: boolean; is_nullable: boolean; is_unique?: boolean; is_auto_increment?: boolean; default_value?: string | null; order_index?: number;
};
export type GenTable = { id: string; physical_name: string; logical_name?: string | null; default_has_pk_auto_increment?: boolean | null; columns: GenColumn[] };
export type GenRelationship = { from_table_id: string; from_column_id: string; to_table_id: string; to_column_id: string; relationship_type: string };
export type GenOptions = { dbms: string; dropFirst?: boolean; comments?: boolean; foreignKeys?: boolean };

export const GEN_DBMS = ['ORACLE', 'MYSQL', 'MARIADB', 'POSTGRESQL', 'MSSQL', 'SQLITE'] as const;

const esc = (s: string | null | undefined) => (s ?? '').replace(/'/g, "''").replace(/\n/g, ' ').replace(/\r/g, '');

function formatDefault(value: string, db: string): string {
  const v = value.trim();
  if (/^\d+$/.test(v)) return v;
  const up = v.toUpperCase();
  if (['NOW()', 'CURRENT_TIMESTAMP', 'SYSDATE', 'CURRENT_DATE'].includes(up)) {
    if (db === 'ORACLE' && up === 'NOW()') return 'SYSDATE';
    if (db === 'POSTGRESQL' && up === 'SYSDATE') return 'CURRENT_TIMESTAMP';
    return up;
  }
  return `'${esc(value)}'`;
}

/** 하위(FK를 가진) 테이블이 먼저 지워지도록 정렬한다. 순환이면 그 자리에서 끊는다. */
function dropOrder(tables: GenTable[], rels: GenRelationship[]): GenTable[] {
  const ids = new Set(tables.map((t) => t.id));
  const children = new Map<string, string[]>();
  for (const r of rels) children.set(r.from_table_id, [...(children.get(r.from_table_id) ?? []), r.to_table_id]);
  const done = new Set<string>();
  const visiting = new Set<string>();
  const order: string[] = [];
  const visit = (id: string) => {
    if (visiting.has(id) || done.has(id)) return;
    visiting.add(id);
    for (const c of children.get(id) ?? []) if (ids.has(c)) visit(c);
    visiting.delete(id);
    done.add(id);
    order.push(id);
  };
  tables.forEach((t) => visit(t.id));
  return order.map((id) => tables.find((t) => t.id === id)!);
}

/**
 * tables: 내보낼 테이블. all: FK가 가리키는 테이블을 찾을 전체 테이블(선택하지 않은 테이블도 참조할 수 있게).
 * 관계는 to 테이블(FK를 가진 쪽)이 tables에 있는 것만 낸다.
 */
export function generateDDL(tables: GenTable[], all: GenTable[], relationships: GenRelationship[], opts: GenOptions): string {
  const db = opts.dbms.toUpperCase();
  const my = db === 'MYSQL' || db === 'MARIADB';
  const q = (name: string) => (my ? `\`${name}\`` : name);
  const comments = opts.comments !== false;
  const out: string[] = [];
  out.push('-- =====================================================', '-- DDL Generated by worktree-studio (erd-vibe)', `-- Database Type: ${db}`, '-- =====================================================', '');

  if (opts.dropFirst) {
    out.push('-- DROP TABLES');
    for (const t of dropOrder(tables, relationships)) {
      out.push(db === 'ORACLE' ? `DROP TABLE ${t.physical_name} CASCADE CONSTRAINTS;` : db === 'POSTGRESQL' ? `DROP TABLE IF EXISTS ${t.physical_name} CASCADE;` : `DROP TABLE IF EXISTS ${q(t.physical_name)};`);
    }
    out.push('');
  }

  for (const table of tables) {
    const cols = [...table.columns].sort((a, b) => (a.order_index ?? 0) - (b.order_index ?? 0));
    const tableAutoInc = table.default_has_pk_auto_increment !== false;
    const autoInc = (c: GenColumn) => Boolean(c.is_auto_increment || (tableAutoInc && c.is_primary_key));
    const defs = cols.map((c) => {
      let type = c.data_type || 'VARCHAR';
      if (c.data_length && !type.includes('(')) type = `${type}(${c.data_length})`;
      let def = `    ${q(c.physical_name)}`;
      let serial = false;
      if (autoInc(c)) {
        const up = type.toUpperCase();
        if (my) def += ` ${type} AUTO_INCREMENT`;
        else if (db === 'POSTGRESQL' && up.includes('INT')) { def += up.includes('BIGINT') ? ' BIGSERIAL' : ' SERIAL'; serial = true; }
        else if (db === 'MSSQL') def += ` ${type} IDENTITY(1,1)`;
        else if (db === 'SQLITE') def += ` ${type} AUTOINCREMENT`;
        else if (db === 'ORACLE' && type === 'NUMBER') def += ` NUMBER GENERATED ALWAYS AS IDENTITY${c.is_primary_key ? ' PRIMARY KEY' : ''}`;
        else def += ` ${type}`;
      } else def += ` ${type}`;
      if (c.is_primary_key && my) def += ' PRIMARY KEY';
      if (!c.is_nullable && !serial) def += ' NOT NULL';
      if (c.is_unique) def += ' UNIQUE';
      if (c.default_value) def += ` DEFAULT ${formatDefault(c.default_value, db)}`;
      if (my && comments && c.logical_name) def += ` COMMENT '${esc(c.logical_name)}'`;
      return def;
    });
    let body = defs.join(',\n');
    if (!my) {
      // Oracle은 IDENTITY로 만든 PK가 컬럼 정의에 이미 PRIMARY KEY를 달고 있다.
      const pk = cols.filter((c) => c.is_primary_key && !(db === 'ORACLE' && autoInc(c) && (c.data_type || '') === 'NUMBER')).map((c) => c.physical_name);
      if (pk.length) body += `,\n    CONSTRAINT PK_${table.physical_name} PRIMARY KEY (${pk.join(', ')})`;
    }
    let stmt = `${my ? `CREATE TABLE IF NOT EXISTS ${q(table.physical_name)}` : `CREATE TABLE ${table.physical_name}`} (\n${body}\n)`;
    if (my) stmt += ` ENGINE=InnoDB DEFAULT CHARSET=utf8mb4${comments && table.logical_name ? ` COMMENT='${esc(table.logical_name)}'` : ''}`;
    out.push(`${stmt};`, '');
    if (comments && (db === 'ORACLE' || db === 'POSTGRESQL')) {
      if (table.logical_name) out.push(`COMMENT ON TABLE ${table.physical_name} IS '${esc(table.logical_name)}';`);
      for (const c of cols) if (c.logical_name) out.push(`COMMENT ON COLUMN ${table.physical_name}.${c.physical_name} IS '${esc(c.logical_name)}';`);
      out.push('');
    }
  }

  const picked = new Set(tables.map((t) => t.id));
  const fks = opts.foreignKeys === false ? [] : relationships.filter((r) => picked.has(r.to_table_id));
  const byId = new Map(all.map((t) => [t.id, t]));
  const lines: string[] = [];
  for (const r of fks) {
    const from = byId.get(r.from_table_id);
    const to = byId.get(r.to_table_id);
    const fromCol = from?.columns.find((c) => c.id === r.from_column_id);
    const toCol = to?.columns.find((c) => c.id === r.to_column_id);
    if (!from || !to || !fromCol || !toCol) continue;
    let s = `ALTER TABLE ${q(to.physical_name)}\n  ADD CONSTRAINT FK_${to.physical_name}_${toCol.physical_name}\n  FOREIGN KEY (${q(toCol.physical_name)}) REFERENCES ${q(from.physical_name)}(${q(fromCol.physical_name)})`;
    if (r.relationship_type === 'one_to_one') s += ' ON DELETE CASCADE';
    else if (r.relationship_type === 'one_to_many' && db !== 'ORACLE') s += ' ON DELETE RESTRICT';
    lines.push(`${s};`, '');
  }
  if (lines.length) out.push('-- FOREIGN KEY CONSTRAINTS', ...lines);
  return out.join('\n');
}
